// Copies the shared header and footer into every page in public/.
//
//   Edit tools/partials/header.html or footer.html, then run:  npm run sync-layout
//
// Each page marks where the shared pieces go with comment markers:
//   <!-- HEADER:START --> ... <!-- HEADER:END -->
//   <!-- FOOTER:START --> ... <!-- FOOTER:END -->
// Everything between a pair of markers is replaced.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const publicDir = path.join(root, 'public');
const partial = (name) => fs.readFileSync(path.join(root, 'tools', 'partials', name), 'utf8').trimEnd();

const parts = [
  { name: 'HEADER', html: partial('header.html') },
  { name: 'FOOTER', html: partial('footer.html') },
];

let changed = 0;
for (const file of fs.readdirSync(publicDir).filter((f) => f.endsWith('.html'))) {
  const filePath = path.join(publicDir, file);
  let page = fs.readFileSync(filePath, 'utf8');
  const original = page;

  for (const { name, html } of parts) {
    // START marker may carry a "(generated by ...)" note after the first run, so match loosely.
    const pattern = new RegExp(`([ \\t]*)<!-- ${name}:START[^>]*-->[\\s\\S]*?<!-- ${name}:END -->`);
    if (!pattern.test(page)) { console.warn(`${file}: no ${name} markers, skipped`); continue; }
    page = page.replace(pattern, (_match, indent) => {
      const body = html.split('\n').map((line) => (line ? indent + '  ' + line : line)).join('\n');
      return `${indent}<!-- ${name}:START (generated by tools/sync-layout.mjs; edit tools/partials/) -->\n${body}\n${indent}<!-- ${name}:END -->`;
    });
  }

  if (page !== original) { fs.writeFileSync(filePath, page); changed++; }
}
console.log(`Updated ${changed} page(s).`);
